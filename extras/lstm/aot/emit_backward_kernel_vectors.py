"""Print the C++ test-vector header for the scalar lstm_backward kernel.

Expected values come from the AOT reference (`_lstm_backward_ref`) evaluated in
float64 and cast to float32; the kernel's job is to reproduce them in scalar
float32. This is a DEV-TIME generator — the output is committed as
extras/lstm/test/lstm_backward_vectors.h (test vectors, not a CI fixture). Re-run
after any reference/spec change:

    python extras/lstm/aot/emit_backward_kernel_vectors.py > extras/lstm/test/lstm_backward_vectors.h

Cases: (a) biases, no state grads; (b) same with nonzero grad_hn/grad_cn;
(c) no biases; (d) T=1.
"""
import pathlib
import struct
import sys
import textwrap

import torch

HERE = pathlib.Path(__file__).resolve().parent
_REPO_ROOT = HERE.parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))
import extras.lstm.aot.etnp_lstm_op  # noqa: E402,F401


def _f32(v: float) -> str:
    f = struct.unpack("f", struct.pack("f", float(v)))[0]
    s = f"{f:.9g}"
    if not any(c in s for c in ".eE"):
        s += ".0"          # 0 -> 0.0: `0f` is not a C++ float literal
    return s + "f"


def _arr(name: str, t) -> str:
    vals = t.detach().to(torch.float32).flatten().tolist()
    return f"inline constexpr float {name}[] = {{{', '.join(_f32(v) for v in vals)}}};\n"


_CASE = textwrap.dedent("""\
    namespace {tag} {{
    inline constexpr int64_t T = {T}, B = {B}, I = {I}, H = {H};
    {body}}}  // namespace {tag}

    """)

_HEADER = textwrap.dedent("""\
    // GENERATED by extras/lstm/aot/emit_backward_kernel_vectors.py — re-run to refresh.
    // Expected gradients come from the float64 AOT reference, cast to float32.
    #pragma once
    #include <cstdint>

    namespace etnp_test_vectors {{

    struct Case {{
      const char* name;
      int64_t T, B, I, H;
      bool has_bias;
      bool has_grad_state;
      const float* input;
      const float* h0;
      const float* c0;
      const float* grad_output;
      const float* grad_hn;
      const float* grad_cn;
      const float* w_ih;
      const float* w_hh;
      const float* b_ih;
      const float* b_hh;
      const float* grad_input;
      const float* grad_h0;
      const float* grad_c0;
      const float* grad_w_ih;
      const float* grad_w_hh;
      const float* grad_b_ih;
      const float* grad_b_hh;
    }};

    {case_ns}inline constexpr Case cases[] = {{
    {rows}
    }};

    inline constexpr int num_cases = {n};

    }}  // namespace etnp_test_vectors
    """)

_ROW = textwrap.dedent("""\
    {{"{name}", {tag}::T, {tag}::B, {tag}::I, {tag}::H, {bias}, {state},
     {tag}::input, {tag}::h0, {tag}::c0, {tag}::grad_output,
     {grad_hn}, {grad_cn},
     {tag}::w_ih, {tag}::w_hh, {b_ih}, {b_hh},
     {tag}::grad_input, {tag}::grad_h0, {tag}::grad_c0,
     {tag}::grad_w_ih, {tag}::grad_w_hh, {tag}::grad_b_ih, {tag}::grad_b_hh}},""")


def _case(tag: str, T: int, B: int, I: int, H: int, bias: bool,
          state_grads: bool, seed: int) -> str:
    g = torch.Generator().manual_seed(seed)
    r = lambda *s, scale=1.0: torch.randn(*s, generator=g, dtype=torch.float64) * scale
    inp, h0, c0 = r(T, B, I), r(B, H), r(B, H)
    w_ih, w_hh = r(4 * H, I, scale=0.5), r(4 * H, H, scale=0.5)
    b_ih = r(4 * H, scale=0.5) if bias else None
    b_hh = r(4 * H, scale=0.5) if bias else None
    grad_output = r(T, B, H)
    grad_hn = r(B, H) if state_grads else None
    grad_cn = r(B, H) if state_grads else None
    outs = extras.lstm.aot.etnp_lstm_op._lstm_backward_ref(
        grad_output, grad_hn, grad_cn, inp, h0, c0, w_ih, w_hh, b_ih, b_hh)

    tensors = [
        ("input", inp), ("h0", h0), ("c0", c0),
        ("grad_output", grad_output),
        ("w_ih", w_ih), ("w_hh", w_hh),
        ("grad_input", outs[0]), ("grad_h0", outs[1]), ("grad_c0", outs[2]),
        ("grad_w_ih", outs[3]), ("grad_w_hh", outs[4]),
        ("grad_b_ih", outs[5]), ("grad_b_hh", outs[6]),
    ]
    if bias:
        tensors += [("b_ih", b_ih), ("b_hh", b_hh)]
    if state_grads:
        tensors += [("grad_hn", grad_hn), ("grad_cn", grad_cn)]

    body = "".join(_arr(n, t) for n, t in tensors)
    return _CASE.format(tag=tag, T=T, B=B, I=I, H=H, body=body)


def main() -> None:
    cases = [
        ("case_a", 3, 2, 2, 3, True, False, 11),
        ("case_b", 3, 2, 2, 3, True, True, 12),
        ("case_c", 3, 2, 2, 3, False, False, 13),
        ("case_d", 1, 2, 2, 3, True, True, 14),
    ]
    case_ns = "".join(_case(*c) for c in cases)
    # The row template is de-indented; indent it into the initializer list here.
    rows = "\n".join(
        textwrap.indent(
            _ROW.format(
                name=tag[5:],
                tag=tag,
                bias="true" if bias else "false",
                state="true" if state_grads else "false",
                grad_hn=f"{tag}::grad_hn" if state_grads else "nullptr",
                grad_cn=f"{tag}::grad_cn" if state_grads else "nullptr",
                b_ih=f"{tag}::b_ih" if bias else "nullptr",
                b_hh=f"{tag}::b_hh" if bias else "nullptr",
            ),
            "  ",
        )
        for tag, _T, _B, _I, _H, bias, state_grads, _seed in cases
    )
    sys.stdout.write(_HEADER.format(case_ns=case_ns, rows=rows, n=len(cases)))


if __name__ == "__main__":
    main()
